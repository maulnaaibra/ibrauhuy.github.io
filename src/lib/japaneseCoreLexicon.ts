function ensureLexicon(): {
  bySurface: Map<string, CoreLexiconEntry>;
  sortedSurfaces: string[];
  maxLen: number;
} {
  if (cachedLexiconBySurface && cachedSurfaceList) {
    return {
      bySurface: cachedLexiconBySurface,
      sortedSurfaces: cachedSurfaceList,
      maxLen: cachedMaxSurfaceLen,
    };
  }
  const bySurface = new Map<string, CoreLexiconEntry>();
  let maxLen = 1;
  for (const row of RAW_CORE_ENTRIES) {
    const parts = row.split('|');
    if (parts.length < 5) continue;
    const surface = parts[0].trim();
    const reading = parts[1].trim();
    const pos = parts[2].trim() as JapanesePosCategory;
    const pitchNumRaw = Number(parts[3]);
    const pitchNum = Number.isFinite(pitchNumRaw) ? pitchNumRaw : undefined;
    const meaning = parts[4].trim();
    const conjType = parts[5]?.trim() as VerbConjType | undefined;
    const lemma = parts[6]?.trim() || surface;
    if (!surface) continue;
    if (surface.length > maxLen) maxLen = surface.length;
    if (!bySurface.has(surface)) {
      bySurface.set(surface, {
        surface,
        reading,
        lemma,
        pos,
        conjType,
        pitchNum,
        pitchPattern: resolvePitchPattern(reading || surface, pitchNum),
        meaning,
      });
    }
  }
  cachedLexiconBySurface = bySurface;
  cachedSurfaceList = Array.from(bySurface.keys());
  cachedMaxSurfaceLen = maxLen;
  return {
    bySurface,
    sortedSurfaces: cachedSurfaceList,
    maxLen,
  };
}

export function lookupCoreLexicon(surfaceOrLemma: string): CoreLexiconEntry | null {
  const { bySurface } = ensureLexicon();
  return bySurface.get(surfaceOrLemma) ?? null;
}

export function getLexiconMaxLen(): number {
  return ensureLexicon().maxLen;
}

export function getCoreParticleSet(): Set<string> {
  const { bySurface } = ensureLexicon();
  const set = new Set<string>();
  for (const [k, v] of bySurface.entries()) {
    if (v.pos === 'particle') set.add(k);
  }
  return set;
}
